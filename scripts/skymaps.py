"""
Stage 2C: generate Makefile rules to produce skymaps for the release.

Writes rules for two release trees:

  Stage 2B (full combined release):
    releases/$(RELEASE)/{event}/C00-Combined.h5 → one skymap per waveform label
    (including C00:Mixed for multi-waveform events)

  Stage 1 (SpinTaylor-only release):
    releases/$(RELEASE)/spintaylor/{event}/C00-Combined.h5 → one skymap,
    C00-IMRPhenomXPHM-SpinTaylor.fits.gz, for events with exactly one
    APPROVED IMRPhenomXPHM production.

Both sets of rules are written to skymaps.mk.

Run from the project directory (after the release HDF5 files exist):
    python ../scripts/skymaps.py .asimov/ledger.yml
"""
import sys
sys.path.insert(0, "..")
from scripts.ledger import (
    load_ledger, get_events, approved_productions, release_label
)

if len(sys.argv) < 2:
    print(f"Usage: {sys.argv[0]} <ledger.yml>", file=sys.stderr)
    sys.exit(1)

data = load_ledger(sys.argv[1])
events = get_events(data)

def emit(s):
    sys.stdout.write(s)

all_skymap_targets = []
all_spintaylor_skymap_targets = []

# ------------------------------------------------------------------
# Stage 2B: full combined release
# ------------------------------------------------------------------
for name, event in events.items():
    productions = list(approved_productions(event))
    if not productions:
        continue
    # The waveform labels that will be in the release HDF5, plus Mixed
    waveform_labels = [
        release_label(settings["waveform"]["approximant"])
        for _, settings in productions
    ]
    if len(waveform_labels) > 1:
        waveform_labels.append("Mixed")

    release_file = f"releases/$(RELEASE)/{name}/C00-Combined.h5"
    event_skymap_targets = []

    for waveform in waveform_labels:
        fits_name = f"C00-{waveform.replace(':', '-')}.fits.gz"
        target = f"releases/$(RELEASE)/{name}/{fits_name}"
        event_skymap_targets.append(target)
        all_skymap_targets.append(target)

        emit(f"{target}: {release_file}\n")
        emit(f"\tmkdir -p $(@D)\n")
        emit(
            f"\t${{LIGO_SKYMAP}} $^ -j 32 --maxpts 2000 "
            f"--outdir $(@D) "
            f"--path 'C00:{waveform}/posterior_samples' "
            f"--fitsoutname {fits_name}\n"
        )
        emit("\n")

    # Convenience phony target per event
    emit(f".PHONY: skymaps-{name}\n")
    emit(f"skymaps-{name}: {' '.join(event_skymap_targets)}\n\n")

if all_skymap_targets:
    emit(".PHONY: all-skymaps\n")
    emit("all-skymaps: " + " \\\n    ".join(all_skymap_targets) + "\n\n")

# ------------------------------------------------------------------
# Stage 1: SpinTaylor-only release
# The skymap is already generated by the summarypages job alongside the
# pesummary metafile; just copy it to the release directory.
# Source: ${WEB_PATH}/{event}/{production}/pesummary/samples/{production}_skymap.fits
# ------------------------------------------------------------------
for name, event in events.items():
    qualifying = [
        production
        for production, settings in approved_bilby_productions(event)
        if settings["waveform"]["approximant"] == "IMRPhenomXPHM"
    ]
    if len(qualifying) != 1:
        continue

    production = qualifying[0]
    label = "IMRPhenomXPHM-SpinTaylor"
    fits_name = f"C00-{label}.fits.gz"
    pesummary_skymap = f"${{WEB_PATH}}/{name}/{production}/pesummary/samples/{production}_skymap.fits"
    release_hdf5 = f"releases/$(RELEASE)/spintaylor/{name}/C00-Combined.h5"
    target = f"releases/$(RELEASE)/spintaylor/{name}/{fits_name}"
    all_spintaylor_skymap_targets.append(target)

    # Depend on the release HDF5 so the target can always be built.
    # If PESummary already produced a skymap, copy it; otherwise generate one.
    emit(f"{target}: {release_hdf5}\n")
    emit(f"\tmkdir -p $(@D)\n")
    emit(f"\tif [ -f {pesummary_skymap} ]; then \\\n")
    emit(f"\t\tgzip -c {pesummary_skymap} > $@; \\\n")
    emit(f"\telse \\\n")
    emit(f"\t\t${{LIGO_SKYMAP}} $< -j 32 --maxpts 2000 --outdir $(@D) \\\n")
    emit(f"\t\t\t--path 'C00:{label}/posterior_samples' \\\n")
    emit(f"\t\t\t--fitsoutname {fits_name}; \\\n")
    emit(f"\tfi\n")
    emit("\n")

    emit(f".PHONY: spintaylor-skymap-{name}\n")
    emit(f"spintaylor-skymap-{name}: {target}\n\n")

if all_spintaylor_skymap_targets:
    emit(".PHONY: all-spintaylor-skymaps\n")
    emit(
        "all-spintaylor-skymaps: "
        + " \\\n    ".join(all_spintaylor_skymap_targets) + "\n"
    )

